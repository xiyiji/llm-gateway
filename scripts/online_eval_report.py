"""Run the online-eval demo over several seeds and write a results table.

Usage: python scripts/online_eval_report.py [--seeds 1 2 3 7 11 13 17 19]
       [--out docs/online-eval-results.md]
"""

import argparse
import json
import statistics
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from scripts.online_eval_demo import run  # noqa: E402


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--seeds", type=int, nargs="+", default=[1, 2, 3, 7, 11, 13, 17, 19])
    parser.add_argument("--out", type=Path, default=Path("docs/online-eval-results.md"))
    args = parser.parse_args()

    runs = [run(seed) for seed in args.seeds]
    rows = []
    for r in runs:
        p = r["phases"]
        on = next((e for e in r["guard_events"] if e["event"] == "guard_on"), None)
        off = next((e for e in r["guard_events"] if e["event"] == "guard_off"), None)
        rows.append({
            "seed": r["seed"],
            "baseline_q": p["1_baseline"]["served_quality"],
            "shift_q_before_guard": p["2_shift_first_100"]["served_quality"],
            "guarded_q": p["3_shift_guarded"]["served_quality"],
            "guarded_q_without_guard": p["3_shift_guarded"]["quality_without_guard"],
            "guarded_cost": p["3_shift_guarded"]["cost_per_1k_usd"],
            "detect_lag": (on["at_request"] - r["shift_started_at_request"]) if on else None,
            "promoted": r["retrain"]["promote"],
            "final_q": p["5_retrained_guard_released"]["served_quality"],
            "final_cost": p["5_retrained_guard_released"]["cost_per_1k_usd"],
            "released_at": off["at_request"] if off else None,
            "judge_spend": r["judge_spend_usd"],
        })

    def med(key, sub=None):
        vals = [x[key] for x in (sub or rows) if x[key] is not None]
        return round(statistics.median(vals), 3) if vals else None

    promoted = [x for x in rows if x["promoted"]]
    lines = [
        "# Online evaluation: simulated traffic-shift results",
        "",
        "Generated by `python scripts/online_eval_report.py`. Simulated provider and judge "
        "(see `scripts/online_eval_demo.py`); the gateway, sampler, guard, shadow scoring "
        "and retraining code are the production code paths. Quality = share of requests "
        "whose served answer was good; cost in USD per 1k requests at the simulated prices.",
        "",
        "| seed | baseline q | first 100 after shift | guarded q | same traffic, no guard | "
        "guarded $/1k | detection lag (req) | retrained router promoted | final q | final $/1k |",
        "|---|---|---|---|---|---|---|---|---|---|",
    ]
    for x in rows:
        lines.append(
            f"| {x['seed']} | {x['baseline_q']} | {x['shift_q_before_guard']} | {x['guarded_q']} | "
            f"{x['guarded_q_without_guard']} | {x['guarded_cost']} | {x['detect_lag']} | "
            f"{'yes' if x['promoted'] else 'no (kept guarded)'} | {x['final_q']} | {x['final_cost']} |")
    lines += [
        "",
        f"Median over {len(rows)} seeds: quality with the guard {med('guarded_q')} vs "
        f"{med('guarded_q_without_guard')} for the same router on the same traffic without it; "
        f"guard switched on {med('detect_lag')} requests after the shift began.",
        f"Retrained router promoted in {len(promoted)} of {len(rows)} seeds"
        + (f"; where promoted, cost fell from a median ${med('guarded_cost', promoted)} to "
           f"${med('final_cost', promoted)} per 1k requests at quality {med('final_q', promoted)}."
           if promoted else "."),
        "Where it was not promoted, the candidate did not beat the guarded router on newer "
        "held-out live requests, so the gateway kept serving the guarded router.",
        "",
    ]
    args.out.parent.mkdir(exist_ok=True, parents=True)
    args.out.write_text("\n".join(lines), encoding="utf-8")
    print("\n".join(lines))
    (Path("var") / "online_eval_report.json").parent.mkdir(exist_ok=True)
    (Path("var") / "online_eval_report.json").write_text(json.dumps(rows, indent=2))


if __name__ == "__main__":
    main()
